import {
  existsSync,
  readFileSync,
  readdirSync,
  writeFileSync,
} from 'node:fs';
import { resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const projectRoot = resolve(fileURLToPath(new URL('..', import.meta.url)));
const lock = JSON.parse(readFileSync(resolve(projectRoot, 'package-lock.json'), 'utf8'));
const rootPackage = JSON.parse(readFileSync(resolve(projectRoot, 'package.json'), 'utf8'));
const directDependencies = new Set(Object.keys(rootPackage.dependencies ?? {}));

function licenseValue(value) {
  if (typeof value === 'string' && value.trim()) return value.trim();
  if (Array.isArray(value)) return value.map(licenseValue).filter(Boolean).join(' OR ');
  if (value && typeof value === 'object') return licenseValue(value.type);
  return 'UNKNOWN';
}

function escapeCell(value) {
  return String(value).replaceAll('|', '\\|').replaceAll('\n', ' ');
}

function repositoryUrl(value) {
  const raw = typeof value === 'string' ? value : value?.url;
  if (!raw) return '';
  const normalized = raw.trim()
    .replace(/^git\+/, '')
    .replace(/^git:\/\/github\.com\//, 'https://github.com/')
    .replace(/^ssh:\/\/git@github\.com\//, 'https://github.com/')
    .replace(/^git@github\.com:/, 'https://github.com/')
    .replace(/^github:/, 'https://github.com/')
    .replace(/\.git(?=$|[?#])/, '');
  if (/^[A-Za-z0-9_.-]+\/[A-Za-z0-9_.-]+(?:[?#].*)?$/.test(normalized)) {
    return `https://github.com/${normalized}`;
  }
  return normalized;
}

function licenseFiles(packageRoot) {
  if (!existsSync(packageRoot)) return [];
  return readdirSync(packageRoot, { withFileTypes: true })
    .filter((entry) => entry.isFile() && /^(licen[cs]e|copying|notice)(\.|$)/i.test(entry.name))
    .map((entry) => entry.name)
    .sort((left, right) => left.localeCompare(right));
}

const byPackage = new Map();
for (const [relativePath, lockEntry] of Object.entries(lock.packages ?? {})) {
  if (!relativePath || lockEntry.dev || !relativePath.startsWith('node_modules/')) continue;
  const packageRoot = resolve(projectRoot, relativePath);
  const manifestPath = resolve(packageRoot, 'package.json');
  if (!existsSync(manifestPath)) continue;
  const manifest = JSON.parse(readFileSync(manifestPath, 'utf8'));
  const name = manifest.name ?? relativePath.split('node_modules/').at(-1);
  const version = manifest.version ?? lockEntry.version ?? 'unknown';
  const key = `${name}@${version}`;
  const files = licenseFiles(packageRoot);
  let license = licenseValue(manifest.license ?? lockEntry.license);
  const texts = files.map((fileName) => ({
    fileName,
    text: readFileSync(resolve(packageRoot, fileName), 'utf8').trim(),
  }));
  if (license === 'UNKNOWN' && texts.some(({ text }) => /permission is hereby granted, free of charge/i.test(text))) {
    license = 'MIT';
  }
  const current = byPackage.get(key);
  if (!current || (current.texts.length === 0 && texts.length > 0)) {
    byPackage.set(key, {
      name,
      version,
      license,
      direct: directDependencies.has(name),
      source: repositoryUrl(manifest.homepage ?? manifest.repository),
      texts,
    });
  }
}

const packages = [...byPackage.values()].sort((left, right) =>
  left.name.localeCompare(right.name) || left.version.localeCompare(right.version),
);
const licenseCounts = new Map();
for (const item of packages) licenseCounts.set(item.license, (licenseCounts.get(item.license) ?? 0) + 1);

const noticeLines = [
  '# Third-Party Notices',
  '',
  'Workbench includes open-source software listed below. This file is generated from the production dependency tree by `npm run notices`.',
  '',
  'Full license and notice texts found in installed packages are collected in `THIRD_PARTY_LICENSES.txt`. Development-only dependencies are not part of this runtime list.',
  '',
  '## License Summary',
  '',
  '| SPDX/license declaration | Packages |',
  '| --- | ---: |',
  ...[...licenseCounts.entries()]
    .sort(([left], [right]) => left.localeCompare(right))
    .map(([license, count]) => `| ${escapeCell(license)} | ${count} |`),
  '',
  '## Components',
  '',
  '| Package | Version | License | Direct | Source |',
  '| --- | --- | --- | --- | --- |',
  ...packages.map((item) => {
    const source = item.source ? `[link](${item.source})` : '';
    return `| ${escapeCell(item.name)} | ${escapeCell(item.version)} | ${escapeCell(item.license)} | ${item.direct ? 'yes' : 'no'} | ${source} |`;
  }),
  '',
  'This inventory is provided for attribution and review. The corresponding package license text controls if metadata and bundled text differ.',
  '',
];

const licenseLines = [
  'WORKBENCH THIRD-PARTY LICENSES',
  '',
  'Generated by: npm run notices',
  'Scope: production dependencies from package-lock.json',
  '',
];
for (const item of packages) {
  licenseLines.push('='.repeat(80));
  licenseLines.push(`${item.name}@${item.version}`);
  licenseLines.push(`Declared license: ${item.license}`);
  if (item.source) licenseLines.push(`Source: ${item.source}`);
  licenseLines.push('');
  if (item.texts.length === 0) {
    licenseLines.push('No standalone license file was present in the installed package.');
    licenseLines.push('Refer to the package source and declared license above.');
    licenseLines.push('');
    continue;
  }
  for (const { fileName, text } of item.texts) {
    licenseLines.push(`--- ${fileName} ---`);
    licenseLines.push(text);
    licenseLines.push('');
  }
}

writeFileSync(resolve(projectRoot, 'THIRD_PARTY_NOTICES.md'), noticeLines.join('\n'), 'utf8');
writeFileSync(resolve(projectRoot, 'THIRD_PARTY_LICENSES.txt'), licenseLines.join('\n'), 'utf8');

console.log(`Wrote notices for ${packages.length} production packages.`);
